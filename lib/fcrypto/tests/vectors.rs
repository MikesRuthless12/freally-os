#[test]
fn ed25519_rfc8032_section_7_1() {
    assert_eq!(ED25519.len(), 5);
    for (name, sk, pk, msg, sig) in ED25519 {
        let seed: [u8; 32] = unhex(sk).try_into().unwrap();
        let public: [u8; 32] = unhex(pk).try_into().unwrap();
        let msg = unhex(msg);
        let expected: [u8; 64] = unhex(sig).try_into().unwrap();
        assert_eq!(ed25519::public_key(&seed), public, "TEST {name}: public key");
        assert_eq!(ed25519::sign(&seed, &msg), expected, "TEST {name}: signature");
        assert!(ed25519::verify(&public, &msg, &expected), "TEST {name}: verify");
        let mut bad = expected;
        bad[0] ^= 1;
        assert!(!ed25519::verify(&public, &msg, &bad), "TEST {name}: tampered R accepted");
        let mut bad = expected;
        bad[40] ^= 1;
        assert!(!ed25519::verify(&public, &msg, &bad), "TEST {name}: tampered S accepted");
        let mut longer = msg.clone();
        longer.push(0);
        assert!(!ed25519::verify(&public, &longer, &expected), "TEST {name}: another message accepted");
    }
}

