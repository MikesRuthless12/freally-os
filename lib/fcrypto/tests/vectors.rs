#[test]
fn sha_one_million_a_streamed_in_odd_pieces() {
    let s1 = "34aa973cd4c4daa4f61eeb2bdbad27316534016f";
    let s256 = "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0";
    let s512 = "e718483d0ce769644e2e42c7bc15b4638e1f98b13b2044285632a803afa973ebde0ff244877ea60a4cb0432ce577c31beb009c5c2c49aa2e4eadb217ad8cc09b";
    let data = vec![0x61u8; 1_000_000];
    let mut h256 = sha2::Sha256::new();
    let mut h512 = sha2::Sha512::new();
    for piece in data.chunks(999) {
        h256.update(piece);
        h512.update(piece);
    }
    assert_eq!(h256.finish().to_vec(), unhex(s256));
    assert_eq!(h512.finish().to_vec(), unhex(s512));
    assert_eq!(sha1(&data).to_vec(), unhex(s1));
}

