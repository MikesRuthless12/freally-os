/// RFC 3720 § B.4 (CRC bytes as transmitted, read little-endian), and the usual check value.
#[test]
fn crc32c_rfc3720_b4() {
    assert_eq!(crc32c(&[0u8; 32]), 0x8A9136AA);
    assert_eq!(crc32c(&[0xFFu8; 32]), 0x62A8AB43);
    let inc: Vec<u8> = (0u8..32).collect();
    assert_eq!(crc32c(&inc), 0x46DD794E);
    let dec: Vec<u8> = (0u8..32).rev().collect();
    assert_eq!(crc32c(&dec), 0x113FDB5C);
    let pdu = unhex("01c000000000000000000000000000001400000000000400000000140000001828000000000000000200000000000000");
    assert_eq!(crc32c(&pdu), 0xD9963A56);
    assert_eq!(crc32c(b"123456789"), 0xE3069283);
}

/// SHA-384 of the same FIPS 180-4 example messages (the hashes from Python's
